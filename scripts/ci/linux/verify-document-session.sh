#!/bin/bash
# Linux の段（tasks.md 5.3 / 要件 8.2、8.3）。判定の本体は POSIX sh の
# `scripts/check-document-session.sh`（ローカルでも同じものを実行できる）。**この段が足すのは
# OS 固有の 3 つだけ**である: 仮想ディスプレイの用意（`xvfb-run`）・配布物の起動の仕方
# （AppImage。FUSE に依存しないよう展開実行する）・展開実行が残す一時物の片付け。
#
# # 何を確かめるか
#
#   1. **正例**: 検証用の形（`--features verification-triggers` の `target/release/jxcel`）を
#      ドキュメント付きで起動し、引き金（`JXCEL_VERIFICATION_SESSION=open,edit,4,save`）が
#      読み込み → 1 回の一括の適用 → 保存を走らせ、**6 つの事実が順に記録される**こと。
#      検査器は起動の形跡を先に確かめ、記録の区切りの後ろだけを数え、保存のバイト数が雛形と
#      異なること・2 回目の保存が同一バイト列であることまで要求する（**決定性は 1 回目の出力を
#      2 回目の入力にしない** — 雛形の新しい写しから 2 回走らせる）。
#      あわせて**この段の側でも**、区切りの後ろに「引き金を読んだ」がちょうど 1 行であることを
#      数える（検査器の内部判定は走行の直前に取った行数から始まるが、段の側で別の区切りを取れば、
#      前の段が書いた行で満たされる経路が閉じる。10.8 の段と同じ規律）。
#   2. **負の対照**: **配布物（AppImage）を渡すと検査器が非 0 で落ちる**こと。配布物は既定の
#      ビルドであり `JXCEL_VERIFICATION_SESSION` を読まない（5.2 の実装。`verification.md`
#      「検証専用のコードの置き場」）。**落ちる理由が「引き金の行の不在」であること**まで要求する
#      — 起動しなかった実行も「事実が欠ける」で落ちるので、理由を見ないと錠前の実測にならない。
#      併せて、**配布物が実際に起動してドキュメントの窓を開いたこと**を検査器の出力から確かめる。
#      さらに、この実行が書いた行に検証専用の記録が 1 行も無いことを記録の側で数える（出力の
#      ダンプに残る前の実行の行では満たせないよう、区切りより後ろだけを見る）。
#   3. **入力が使えない場合**: **存在しない実行ファイルを渡すと検査器が 2 で落ちる**こと。
#      `verification.md` の規約は「入力が無いときに 0 を返さない」であり、1（逸脱）でもない —
#      この 1 呼び出しは起動を伴わないので、段に置く費用がほぼ無い。
#
# # 実測する形の分担（配布物と検証用の形）
#
# 検証専用の引き金を読むのは**検証用の形**だけである（10.4 の段が
# `JXCEL_VERIFICATION_BUILD=1 npx tauri build --no-bundle --features verification-triggers` で
# 作った `target/release/jxcel`）。配布物（直前の「Build platform bundle」が作った AppImage）は
# 同じ環境変数を無視する — これがこの段の負の対照である。**どちらもこの段が消費するだけで、
# ビルドはしない**（10.4 の段がビルドの位置である）。
#
# # 証拠が何を証明し、何を証明しないか
#
#   - 証明する: **配布物の中核の経路**（`document-format` の読み込み → `Document::set_cells` の
#     一括 → `document-format` の書き出し）が、**このランナーで**実物のドキュメントに対して
#     動き、変更が保存のバイト列に届き、同じ入力の 2 回目が同一バイト列になること。判定は
#     アプリ自身の記録（`[検証] セッション: ` の 6 行）と、保存先のファイルの大きさ・バイト列で
#     行う。**画面もウィンドウツリーも読まない** — 3 OS で同じ判定を閉じるためであり、
#     「ウィンドウが開いたこと」は記録で確かめている（描画の成立は 10.4 の段の担当である。
#     このランナーのソフトウェアラスタライザでは初回描画の期限が 3 秒をわずかに超えることが
#     あり、**描画の成立に依存させるとこの段が偽の失敗をする**）。
#   - 証明しない: 画面の見え方（4.2 の提示・4.3 の状態表示）、保存先の選択の提示（3.5）、
#     メニューからの「保存」（3.6）。いずれも別の段 / 別のタスクの担当である。
#   - **ローカルで閉じられないもの**: macOS / Windows の実行はこの開発機では行えない。この段の
#     3 つの確かめは 3 OS で同じ検査器を通るが、**走らせた事実は OS ごとの段が残す**。
#
# # 位置
#
# 配布物を起動する段である（負の対照）。配布物（AppImage）の起動ではラッパーが本体を切り離すため、
# 検査器の片付けが本体へ届かないことがある（実測。8.2 の節の申し送り）— CI では `xvfb-run` が
# 各呼び出しを包むので**仮想ディスプレイの終了が本体を終わらせる**が、その終了を待たずに次の
# 起動が始まると単一インスタンスの機構に引き継がれうる。したがってこの段は、**配布物を起動する
# 段のまとまりの中**（10.2 の「配布物の負の対照」の直前）に置く。あちらは「自分より後ろに
# 配布物を起動する段が無い」ことを前提にしているため、**あちらより前**でなければならない。
#
# 展開実行（`APPIMAGE_EXTRACT_AND_RUN=1`）は AppImage のランタイムが一時領域へ自分を展開する。
# 検査器はプロセスを木ごと終了するが、**ランタイムの後始末は走らない**ので、この段が作った
# 展開先をここで片付ける（残すと後続の段が偽の失敗をする。10.8 の段と同じ）。

set -eu
# 4.4 の解決（Linux はアプリケーションデータ領域の下の logs。空の XDG_DATA_HOME は
# 未設定として $HOME へ落ちる — アプリ側の解決と同じ）。
record="${XDG_DATA_HOME:-$HOME/.local/share}/com.jxcel.app/logs/jxcel.log"
echo "診断記録: $record"
# 5.2 の引き金が書き換える行数。**保存のバイト数が雛形と変わる値**でなければならない
# （5.2 の実測: 行数 1〜25・39・40 の差分は −1〜+24 で 0 は無い。4 は 2140 B → 2147 B）。
rows=4
# 起動引数に渡す雛形（40 行 × 3 列、2140 B）。**検査器はこの雛形をそのまま使わず、走行ごとに
# 新しい写しを作る**（雛形を書き換えないことと、2 回目の走行が 1 回目の出力を入力にしないこと）。
template=crates/document-format/tests/fixtures/golden/v1/anchored.jxcel
if [ ! -f "$template" ]; then
  echo "NG: 雛形のドキュメントがありません: $template" >&2
  exit 2
fi

# 配布物（AppImage）。**1 つの glob に一致する最初のものを選ぶ**（既存の段と同じ扱い）。
set -- target/release/bundle/appimage/*.AppImage
appimage=$1
if [ ! -f "$appimage" ]; then
  echo "NG: 配布物（AppImage）がありません: $appimage（直前の「Build platform bundle」が先に必要）" >&2
  exit 2
fi
# 展開実行で起動するので絶対パスへ直す（検査器が作業領域へ `cd` しないが、段の側で
# 相対のまま扱うと、後から `cd` を足したときに壊れる）。
appimage=$(CDPATH='' cd -- "$(dirname -- "$appimage")" && pwd)/$(basename -- "$appimage")

if [ ! -x target/release/jxcel ]; then
  echo "NG: 検証用の形がありません: target/release/jxcel（--features verification-triggers のビルドが先に必要。10.4 の段が作ります）" >&2
  exit 2
fi

# 記録の行数を区切りのために読む（この段の判定は**各呼び出しの直前の行数より後ろ**だけを見る。
# 記録は追記式であり、検査器は失敗のときに末尾を出力へダンプするので、出力全体を `grep` すると
# 前の呼び出しの行で満たされうる）。
record_lines() {
  if [ -f "$record" ]; then wc -l < "$record" | tr -d ' '; else echo 0; fi
}
# `<開始行数>` より後の行だけから `grep -E` の一致数を出す（記録が無ければ 0）。
count_after() {
  if [ ! -f "$record" ]; then echo 0; return 0; fi
  tail -n "+$(( $1 + 1 ))" "$record" 2>/dev/null | grep -c -E "$2" || true
}

# **展開実行が残す一時物をトラップでも片付ける。** 検査器はプロセスを木ごと終了するが、
# AppImage のランタイムの後始末は走らないので、展開先は呼び出し側（この段）の持ち物である。
# 末尾の 1 回だけでは、途中で落ちたときに残る（後続の段が偽の失敗をする）— `set -eu` の下では
# **どの行で落ちても**このトラップが走る。
# shellcheck disable=SC2329 # 下の trap から呼ばれる（shellcheck は trap を追えない）
cleanup_extracted() {
  # AppImage のランタイムは `$TMPDIR` を尊重する（実測: `TMPDIR=/tmp/xyz` なら
  # `/tmp/xyz/appimage_extracted_…` が生成され `/tmp` には出ない）。したがって既定の `/tmp` を
  # 直書きせず、解決済みの一時領域を辿る。
  rm -rf "${TMPDIR:-/tmp}"/appimage_extracted_* 2>/dev/null || true
}
trap cleanup_extracted EXIT INT TERM

# 検査器を仮想ディスプレイの下で走らせる（GUI アプリを起動するため。10.8 の段と同じ包み方）。
xvfb_check() {
  xvfb-run -a --server-args="-screen 0 1280x1024x24" \
    sh scripts/check-document-session.sh "$1" "$2" "$record" "$template" "$rows"
}

echo "--- 1/3 正例: 検証用の形で引き金の走行を 2 回行う（読み込み → 一括の適用 → 保存。2 回目は決定性）"
before_pos=$(record_lines)
xvfb_check target/release/jxcel 60
# **この段の区切り**でも事実を数える（前の段の行では満たせない）。
if [ "$(count_after "$before_pos" '引き金を読んだ: 書き換える行数 = '"$rows"'$')" -ne 2 ]; then
  echo "NG: 正例で「引き金を読んだ」の行が 2 行ではありません（2 回の走行で 2 行が期待。前の段の行では満たせない）" >&2
  exit 1
fi
if [ "$(count_after "$before_pos" '保存した: バイト数 = ')" -ne 2 ]; then
  echo "NG: 正例で「保存した」の行が 2 行ではありません（2 回の走行で 2 行が期待）" >&2
  exit 1
fi
echo "OK: 正例: 検証用の形で 2 回の走行が成立し、6 つの事実がそれぞれ 2 行そろった"

echo "--- 2/3 負の対照: 配布物（AppImage）を渡すと検査器が非 0 で落ちること"
before_neg=$(record_lines)
rc=0
# **展開実行で起動する**（FUSE が使えないランナーでも通る。機能そのものの自己完結性は
# 10.3 / 10.4 の段と `check-shipping-bundle.sh` が担う）。
output=$(APPIMAGE_EXTRACT_AND_RUN=1 xvfb_check "$appimage" 45 2>&1) || rc=$?
printf '%s\n' "$output"
if [ "$rc" -eq 0 ]; then
  echo "NG: 配布物に対して検査器が成功してしまった（既定のビルドに検証専用の引き金が入っている）" >&2
  exit 1
fi
if [ "$rc" -eq 2 ]; then
  echo "NG: 負の対照が「入力が使えない」で落ちた（検査器が走っていない。配布物のパスか実行権限を確かめてください）" >&2
  exit 1
fi
# **落ちた理由が「引き金の行の不在」であること。** 起動しなかった実行も事実の欠落で落ちるので、
# 理由を見ないと錠前の実測にならない。
if ! printf '%s\n' "$output" | grep -q "'引き金を読んだ' の行が 1 行ではありません"; then
  echo "NG: 負の対照が「引き金の行の不在」以外の理由で落ちた（検査器が錠前を見ていない可能性がある）" >&2
  exit 1
fi
# **配布物が実際に起動してドキュメントの窓を開いたこと**（検査器が出す起動の形跡の行）。
if ! printf '%s\n' "$output" | grep -q '起動の形跡: .*ウィンドウを開いた: label=doc-'; then
  echo "NG: 負の対照で配布物が起動した形跡がありません（起動しなかった実行を錠前の実測と取り違えない）" >&2
  exit 1
fi
# **この実行が書いた行**に検証専用の記録が 1 行も無いこと（前の呼び出しの行では判定しない）。
if [ "$(count_after "$before_neg" '引き金を読んだ: 書き換える行数 = ')" -ne 0 ]; then
  echo "NG: 配布物が検証専用の引き金を読んでいます（既定のビルドに検証専用の経路が入っている）" >&2
  exit 1
fi
echo "OK: 反証: 配布物は起動してドキュメントの窓を開いたが、引き金を読まないため検査器が非 0 で落ちた"

echo "--- 3/3 入力が使えない場合: 存在しない実行ファイルなら 2 で落ちること"
rc=0
output=$(sh scripts/check-document-session.sh "$PWD/no-such-verification-build" 10 "$record" "$template" "$rows" 2>&1) || rc=$?
printf '%s\n' "$output"
if [ "$rc" -ne 2 ]; then
  echo "NG: 入力が使えない場合に 2 を返しませんでした（返した値: ${rc}。1 = 逸脱 / 0 = 適合はどちらも誤り — 入力の不在を適合とも逸脱とも報告しない）" >&2
  exit 1
fi
echo "OK: 入力が使えない場合（実行ファイルの不在）は 2 で落ちた"

# 展開実行が残した一時物を片付ける（**トラップが本体**である — 途中で落ちても走る。
# ここは正常終了の経路で、片付いたことを出力に残すために呼ぶ）。`cleanup_extracted` を
# そのまま呼ぶ（`$TMPDIR` の解決を 2 箇所に写さない）。
cleanup_extracted
echo "OK: Linux: 引き金の走行（正例 2 回・負の対照・入力の不在）を 3 つとも実測した（画面の見え方とメニューからの保存は別の段の担当）"
