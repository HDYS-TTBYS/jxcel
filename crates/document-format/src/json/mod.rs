//! 決定的な JSON 出力（タスク 3.1。要件 2.4, 3.3, 3.6）。
//!
//! design「DeterministicJson」の責務を本モジュール 1 か所で引き受ける:
//! UTF-8 出力、キー順序の固定、汎用 JSON 値型とハッシュマップを経由しない経路、
//! スキーマ由来の動的な列集合の明示的な整列、数値の正規化（`-0.0` は `0`、
//! NaN / Infinity の拒否）。書き出し口の実装は [`determinism`] にあり、
//! 本モジュールは層の規則を記述し、その公開面を再エクスポートする。
//!
//! # 出力の規則
//!
//! 1. 出力は **UTF-8 のコンパクトな JSON** である（余分な空白・改行を入れない）。
//!    非 ASCII は生の UTF-8 バイトとして書き、`\u` エスケープへ落とさない
//!    （要件 2.4: すべての JSON エントリは UTF-8 のテキスト）。行末の改行は
//!    **付与しない**: 1 行 1 オブジェクトの行末規則は NDJSON コーデック
//!    （タスク 3.3）の担当であり、本モジュールは値の直列化だけを行う。
//! 2. キー順序は **書き出し対象の宣言順**に固定する（要件 3.3）。構造体は
//!    フィールド宣言順、動的な列集合は呼び出し元が与えた順序であり、
//!    **並べ替え・ソート・辞書順化を一切しない**。
//! 3. `serde_json` の汎用 JSON 値型・マップ型、およびハッシュマップを経由する
//!    経路を持たない。汎用 JSON 値型は整数と浮動小数の区別を保持できないため
//!    `5`（整数）と `5.0`（浮動小数）の区別が書き出しで化け（要件 3.6）、
//!    ハッシュマップは反復順が実行ごとに変わるため決定性を壊す（要件 3.3）。
//!    `serde_json` は直列化の配線にのみ使う（[`crate::value`] と同じ方針）。
//! 4. 数値の正規化は [`crate::value`] の実装をそのまま使う: `-0.0` は `0` として
//!    出力し、NaN / Infinity は [`crate::DocumentError::NonRepresentableNumber`]
//!    として拒否する。型付きエラーとセル位置を運べるのはセル単位の書き出し口
//!    （[`crate::value::to_json_bytes`]）だけであり、本モジュールは正規化も
//!    遮断も**再実装しない**（第二の規約を作らない）。
//! 5. 直列化に失敗したとき、書き出し先へ **1 バイトも書かない**。各書き出し口は
//!    一時バッファへ組み立て、全体が成功した後にのみ書き込み先へ渡す
//!    （途中まで書かれた JSON はどのみち不正であり、要件 3.3 系が禁じる
//!    「無効な JSON を書く」に当たる）。
//!
//! # 列順序は呼び出し元が与える
//!
//! 本クレートはスキーマを解釈しない（行エントリはスキーマ解釈なしでモデルへ
//! 戻らなければならない）ため、どの列をどの順序で書くかを自分では決められない。
//! スキーマ由来の動的な列集合の順序は **呼び出し元（スキーマ側）が与える**契約で
//! あり、[`determinism::write_ordered_object`] は与えられた順序をそのまま出力する。
//! 決定性はこの契約に依存する（design「DeterministicJson」Risks:
//! 「動的な列集合の順序をスキーマ側に依存する」を、モジュール境界として明示した
//! ものである）。
//!
//! # 未知フィールドの保持（前方互換。要件 6.2 / 6.3）
//!
//! バージョン付きのパート構造体は、自分のバージョンが解釈しないフィールドを破棄せず、
//! **原文の位置**へ差し戻して書き戻す。この機構は本モジュールの 1 か所
//! （[`determinism`]）にあり、[`PreservedField`] / [`PreservedFields`]（読み込み時の
//! 保持）と [`PreservingObjectWriter`]（書き出し時の差し戻し）が公開面である。
//! 値は `serde_json::value::RawValue` が捕捉した原文のバイト列であり、汎用 JSON 値型を
//! 経由しない（規則 3 の例外ではなく、規則 3 を満たすための仕組みである）。
//!
//! # 依存方向
//!
//! `Ids / Value / EntryName → Model → Json → Parts → Container → Api` の一方向
//! （design「Architecture Integration」）。本モジュールは [`crate::value`] /
//! [`crate::error`] にのみ依存し、`parts` / `container` / `model` に依存しない。

pub mod determinism;

pub use determinism::{
    write_cell, write_json, write_ordered_object, PreservedField, PreservedFields,
    PreservingObjectWriter,
};
