//! 日時の厳密な解釈と正準表記（design.md「コンポーネントとファイルの対応」の
//! `TemporalValue`。tasks.md 2.3 が実装する。要件 2.4, 7.3）。
//!
//! # 層の鎖（design.md「内部の依存の向き」）
//!
//! `error / types → declaration → registry → compile → { coerce, validate } → write →
//! evolution → api`。本モジュールは [`super`]（`TypeCatalog`）の下に置かれ、日付・civil
//! 日時・オフセット付き瞬時の**厳密な解釈と正準表記**だけを所有する。
//!
//! # タイムゾーンの扱いは 2 値に限る（design.md「組込型カタログと `CellValue` への写像」）
//!
//! IANA のタイムゾーン注釈付きの値（`jiff` の `Zoned`）は初版では扱わない。扱うには
//! タイムゾーンデータベースを実行ファイルへ同梱することになり、単一実行ファイルのサイズに
//! 直接効くためである。`offset: "required"` のオフセット付き瞬時があれば台帳用途の要求は
//! 満たせる。`jiff` の feature は tasks.md 1.1 が固定している（tzdb を同梱しない）。
//!
//! # 環境で変わる解釈をしない（要件 7.3）
//!
//! `2026/09/12` のような書式、曜日名、和暦、タイムゾーン名の略号、桁区切りのある数値は
//! **すべて拒否**する。`jiff` は既定でこれらを拒否するため、規則の実装と道具の既定が一致
//! している（design.md「Coerce Layer / Coercer」）。
//!
