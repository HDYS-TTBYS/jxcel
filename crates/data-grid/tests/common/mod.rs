//! 統合テスト（`tests/*.rs`）とベンチ（`benches/*.rs`）が共有する道具の置き場
//! （タスク 1.4。要件 1.1, 11.7）。
//!
//! `tests/` 配下の各 `.rs` は独立したテストバイナリであり、あるテストクレートの関数を
//! 別のテストクレートから使う機構が無い。さらに `benches/` から `tests/` のモジュールを
//! そのまま取り込むこともできない。したがって共有する道具はこのサブモジュールへ置き、
//! テストは `mod common;` を宣言して取り込み、**ベンチは相対パスで取り込む**
//! （`#[path = "../tests/common/mod.rs"] mod common;`。tasks.md 1.4「ベンチからは相対パス
//! 指定でこの共有モジュールを取り込む」）。
//!
//! # 何を置くか
//!
//! [`sample`] — 指定した行数・列数のシートと、それに適合するスキーマ宣言の生成器である。
//! 行数・列数・違反の割合・種だけが [`sample::SampleOptions`] で変わり、入口は
//! [`sample::sample`] 1 つである。群ごとのテストとベンチはこの同じ標本を共有する
//! （写しを作らない）。
//!
//! **決定性の契約**（何が同一で、何が同一でないか）は [`sample`] のモジュール docs が
//! 唯一の源である。要点だけをここに繰り返す: 同じ引数の 2 回の組み立ては、**識別子
//! （行識別子とシート識別子）を除いて**一致する。生の値・生の宣言テキスト・文書の
//! バイト列は比較してはならない。
//!
//! # テストごとに使う部分集合が違う
//!
//! 各テストバイナリが使う部分集合は違うため、バイナリによっては未使用の項目が生じる。
//! 検証対象を 1 箇所へ集約する利点が、バイナリごとの未使用項目より大きいので、
//! モジュール全体に `#![allow(dead_code)]` を置く（この意図を消さないこと）。
//! `document-format` の `tests/common/mod.rs` と同じ慣用である。
#![allow(dead_code)]

