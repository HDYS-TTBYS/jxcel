//! 診断の保持方針・秘匿規則・書き出し束ね（要件 8.1、8.3〜8.7）。
//!
//! 保持する記録の合計サイズの上限 50 MB という**方針値**をここで定義する（要件 8.5）。
//! 採用する記録機構（`tauri-plugin-log`）の既定は 40 KB / 1 世代であり、アダプタ側が明示的に
//! 上書きしなければ桁が違う（research.md 決定 6）— 本モジュールはその上書きの源になる値を
//! 持つ。ドキュメントのセル値とスキーマの内容は `Redacted` 型を通してのみ記録経路に触れられる
//! （要件 8.4）。記録を外部へ送信する経路は持たない（要件 8.3）。
//!
//! 記録機構そのものの登録はアダプタ層（`AppLifecycle`）が行う。本モジュールは方針だけを持ち、
//! Tauri 非依存を保つ（design.md「DiagnosticsPolicy」）。本タスク（1.2）では骨組みのみを置く。
//! 実体は tasks.md 4.4 が追加する。
