//! ウィンドウの終了拒否の仲介 — ドキュメントを所有する機能へ終了の可否を問い合わせ、
//! 拒否された場合はウィンドウを閉じない。
//!
//! 所有: `WindowCloseGate`（design.md「Components and Interfaces → Adapter Layer」）。
//! 要件: 2.6。
//!
//! 本ファイルはタスク 1.3 が置いた空のモジュール骨組みである。実体を埋めるのはタスク 7.6。
//! 実装上の制約（design.md より）:
//!
//! - 可否は基盤側で非ブロッキングに読まれるため、**待ってから拒否することはできない**。
//!   フロントエンド側の購読が登録されているだけで自動的に拒否される仕組みに、非同期の往復を
//!   載せる。
//! - 拒否が解除された後に閉じるときは `destroy()` のみを使う。`close()` は終了要求を
//!   再発火し、拒否に再突入する。
